import Fastify, { type FastifyInstance } from "fastify";
import cors from "@fastify/cors";
import rateLimit from "@fastify/rate-limit";
import { config } from "./config.js";
import { traceIdPlugin } from "./plugins/trace-id.js";
import { errorHandlerPlugin } from "./plugins/error-handler.js";
import { authPlugin } from "./plugins/auth.js";

/**
 * Builds the Fastify app with shared infra wired in (CORS, trace id, error handling,
 * auth decorators, rate-limit plugin registered but not global — routes opt in via
 * `config: { rateLimit: {...} }`, used only by POST /auth/login).
 *
 * Domain route plugins are registered in src/server.ts, one `app.register(...)` per
 * domain — add yours there, do not edit this file for a new domain.
 */
export async function buildApp(): Promise<FastifyInstance> {
  const app = Fastify({
    logger: {
      level: config.NODE_ENV === "development" ? "info" : "warn",
      ...(config.NODE_ENV === "development"
        ? { transport: { target: "pino-pretty", options: { colorize: true } } }
        : {}),
    },
  });

  await app.register(cors, {
    origin: true,
    credentials: true,
    methods: ["GET", "POST", "PUT", "DELETE", "PATCH", "OPTIONS"],
    allowedHeaders: ["Authorization", "Content-Type", "X-Trace-Id"],
    exposedHeaders: ["X-Trace-Id", "Content-Disposition"],
  });
  await app.register(rateLimit, { global: false });
  await app.register(traceIdPlugin);
  await app.register(errorHandlerPlugin);
  await app.register(authPlugin);

  app.get("/internal/health", async () => ({ status: "UP" }));

  return app;
}
